'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),guides=require('./block-guides.cjs'),{svg}=require('./render-blocks.cjs');
fs.mkdirSync(path.join(root,'assets/blocks'),{recursive:true});
guides.forEach((g,i)=>fs.writeFileSync(path.join(root,'assets/blocks',String(i+1)+'.svg'),svg(g,i)));
fs.writeFileSync(path.join(root,'block-guides.js'),"'use strict';\n// Generated by node scripts/build-blocks.cjs. Edit scripts/block-guides.cjs instead.\nconst BLOCK_GUIDES="+JSON.stringify(guides.map(({blocks,...rest})=>rest),null,2)+";\n");
console.log('Generated 6 connected SVG diagrams and reading guides.');
